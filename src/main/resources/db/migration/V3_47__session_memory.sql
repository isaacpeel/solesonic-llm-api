-- The model's memory: Spring AI's JDBC session store, copied from spring-ai-session-jdbc's
-- schema-postgresql.sql (2.1.0-RC2). The repository writes UTC itself, so the columns stay TIMESTAMP.
create table if not exists ai_session (
    id            varchar(255) not null primary key,
    created_at    timestamp    not null,
    expires_at    timestamp,
    metadata      text         not null,
    event_version bigint       not null default 0
);

create index if not exists idx_ai_session_expires_at
    on ai_session (expires_at);

create table if not exists ai_session_index (
    session_id varchar(255) not null,
    attr_name  varchar(255) not null,
    attr_value varchar(512) not null,
    primary key (session_id, attr_name),
    constraint fk_ai_session_index_session
        foreign key (session_id) references ai_session (id) on delete cascade
);

create index if not exists idx_ai_session_index_name_value
    on ai_session_index (attr_name, attr_value);

create table if not exists ai_session_event (
    seq             bigint generated by default as identity,
    id              varchar(255) not null primary key,
    session_id      varchar(255) not null,
    "timestamp"     timestamp    not null,
    event_type      varchar(64)  not null default 'MESSAGE',
    message_type    varchar(20),
    message_content text,
    payload         text         not null,
    synthetic       boolean      not null default false,
    metadata        text         not null,
    constraint fk_ai_session_event_session
        foreign key (session_id) references ai_session (id) on delete cascade
);

create index if not exists idx_ai_session_event_session_seq
    on ai_session_event (session_id, seq);

create index if not exists idx_ai_session_event_session_type_seq
    on ai_session_event (session_id, event_type, seq);

-- What the session knows about a chat_message row: null (not seen yet), the id of the event holding
-- it, 'advisor-reply' or 'outside-window'. Read only by the session code.
alter table chat_message add column session_event_id varchar(255);

create index chat_message_unlinked_idx
    on chat_message (chat_id, timestamp)
    where session_event_id is null;
